import puppeteer from 'puppeteer-core';
const [out, preset, T, cx, cy, cz, tx, ty, tz, overlay = 'off', color = 'normal'] = process.argv.slice(2);
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true,
  args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist', '--window-size=1600,1000'], defaultViewport: { width: 1600, height: 1000 }, protocolTimeout: 600000 });
const page = await browser.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
page.on('dialog', (d) => d.accept());
await page.goto('http://localhost:4196/?devtools', { waitUntil: 'networkidle0' });
await page.waitForFunction(() => window.__ds && window.__r3f);
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const ev = (fn, ...a) => page.evaluate(fn, ...a);
await ev((p) => window.__ds.actions.loadFirePreset(p), preset);
await wait(500);
await ev(() => window.__ds.actions.runExperiment());
await page.waitForFunction(() => window.__ds.sim.isLoaded() && window.__ds.simStore.getState().status === 'running', { timeout: 60000 });
await ev((T) => { const s = window.__ds.sim; s.pause(); s.advance(T - s.getTime()); }, Number(T));
await ev(([o, c, g]) => { const v = window.__ds.view.getState(); v.setThermalViz({ field: 'off', objects: false, isotherms: false }); v.setFireViz({ overlay: o, glow: g }); v.setStructureViz({ color: c }); }, [overlay, color, process.env.GLOW !== '0']);
await ev((p) => { const st = window.__r3f.get(); st.camera.position.set(p[0], p[1], p[2]); st.controls.target.set(p[3], p[4], p[5]); st.controls.update(); }, [cx, cy, cz, tx, ty, tz].map(Number));
await wait(1500);
await page.screenshot({ path: `${out}/${preset}-${T}-${overlay}.png` });
console.log('errors', errors.length, errors.slice(0, 3));
await browser.close();
