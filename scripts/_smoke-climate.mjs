import puppeteer from 'puppeteer-core';
const out = process.argv[2];
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist', '--window-size=1600,1000'], defaultViewport: { width: 1600, height: 1000 }, protocolTimeout: 1800000 });
const page = await browser.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
page.on('dialog', (d) => d.accept());
await page.goto('http://localhost:4199/?devtools', { waitUntil: 'networkidle0' });
await page.waitForFunction(() => window.__ds && window.__r3f);
await page.evaluate(() => { localStorage.setItem('ds.hazardTab', 'experiment'); localStorage.setItem('ds.bottomHeight', '420'); });
await page.reload({ waitUntil: 'networkidle0' });
await page.waitForFunction(() => window.__ds && window.__r3f);
await page.evaluate(() => window.__ds.actions.loadClimatePreset('heavySnowfall'));
await new Promise((r) => setTimeout(r, 1500));
await page.screenshot({ path: out + '/smoke-editor.png' });
await page.evaluate(() => { for (const b of document.querySelectorAll('button')) if (/실험 실행|Run experiment/.test(b.textContent)) { b.click(); break; } });
await page.waitForFunction(() => window.__ds.sim.isLoaded() && window.__ds.simStore.getState().status === 'running', { timeout: 120000 });
await page.evaluate(() => { const s = window.__ds.sim; s.pause(); s.advance(120); });
await page.evaluate(() => { const st = window.__r3f.get(); st.camera.position.set(30, 50, 70); st.controls.target.set(0, 0, 0); st.controls.update(); window.__ds.sim.play(); });
await new Promise((r) => setTimeout(r, 2500));
await page.screenshot({ path: out + '/smoke-run.png' });
const c = await page.evaluate(() => { const c = window.__ds.simStore.getState().climate; return c && { snow: c.stats.snowMass, depth: c.stats.maxSnowDepth, res: c.stats.waterResidual, ms: c.ms }; });
console.log(JSON.stringify({ c, errors }));
await browser.close();
